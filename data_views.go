type CreateDataViewOptions struct {
	_ [0]func()

	// Override replaces the data view with the same ID instead of failing
	// with [ErrBadRequest].
	Override bool `url:"-"`
}

// ListDataViewsOptions are the options of [DataViewsService.List].
type ListDataViewsOptions struct {
	_ [0]func()
}

// List returns the data views of the client's space.
//
// Kibana API: GET /api/data_views
//
// Kibana API docs: https://www.elastic.co/docs/api/doc/kibana/operation/operation-getalldataviewsdefault
func (s *DataViewsService) List(ctx context.Context, opt *ListDataViewsOptions, opts ...RequestOption) ([]*DataViewSummary, *Response, error) {
	var result dataViewEnvelope[[]*DataViewSummary]
	resp, err := s.client.do(ctx, http.MethodGet, "/api/data_views", nil, &result, opt, opts)
	if err != nil {
		return nil, resp, err
	}
	return result.DataView, resp, nil
}

// GetDataViewOptions are the options of [DataViewsService.Get].
type GetDataViewOptions struct {
	_ [0]func()
}

// Get returns a data view of the client's space.
//
// Kibana API: GET /api/data_views/data_view/{viewId}
//
// Kibana API docs: https://www.elastic.co/docs/api/doc/kibana/operation/operation-getdataviewdefault
func (s *DataViewsService) Get(ctx context.Context, id string, opt *GetDataViewOptions, opts ...RequestOption) (*DataView, *Response, error) {
	if err := requireID("data view ID", id); err != nil {
		return nil, nil, err
	}
	return s.dataView(ctx, http.MethodGet, pathf("/api/data_views/data_view/%s", id), nil, opt, opts)
}

// Create creates a data view in the client's space. It sends every field
// except Fields and Version. Data views with the same title
// are allowed; an existing ID fails with [ErrBadRequest] unless
// opt.Override is set.
//
// The first data view of a space becomes its default data view.
//
// Kibana API: POST /api/data_views/data_view
//
// Kibana API docs: https://www.elastic.co/docs/api/doc/kibana/operation/operation-createdataviewdefaultw
func (s *DataViewsService) Create(ctx context.Context, dv *DataView, opt *CreateDataViewOptions, opts ...RequestOption) (*DataView, *Response, error) {
	if dv == nil {
		return nil, nil, errors.New("kibana: data view must not be nil")
	}
	if dv.Title == "" {
		return nil, nil, errors.New("kibana: data view Title must not be empty")
	}
	body := &dataViewCreate{DataView: dataViewCreateFields{
		ID:              dv.ID,
		Title:           dv.Title,
		Name:            dv.Name,
		TimeFieldName:   dv.TimeFieldName,
		AllowNoIndex:    dv.AllowNoIndex,
		SourceFilters:   dv.SourceFilters,
		FieldFormats:    dv.FieldFormats,
		RuntimeFieldMap: dv.RuntimeFieldMap,
		FieldAttrs:      dv.FieldAttrs,
		Namespaces:      dv.Namespaces,
		AllowHidden:     dv.AllowHidden,
		Type:            dv.Type,
		TypeMeta:        dv.TypeMeta,
	}}
	if opt != nil {
		body.Override = opt.Override
	}
	return s.dataView(ctx, http.MethodPost, "/api/data_views/data_view", body, nil, opts)
}

// UpdateDataViewOptions are the options of [DataViewsService.Update].
type UpdateDataViewOptions struct {
	_ [0]func()

	// RefreshFields reloads the fields from Elasticsearch.
	RefreshFields bool `url:"-"`
}

// Update updates a data view of the client's space. Read it with
// [DataViewsService.Get], modify it, and pass it back:
//
//   - Name, TimeFieldName and AllowNoIndex are always sent, so "" clears
//     the name and the time field.
//   - An empty Title keeps the stored title.
//   - SourceFilters, FieldFormats and RuntimeFieldMap are kept when nil, and
//     replaced when not nil: an empty map removes all runtime fields.
//   - ID, FieldAttrs, Namespaces and AllowHidden are not sent, because
//     Kibana rejects them, nor Fields and Version, which Kibana sets.
//     Change field attributes with [DataViewsService.UpdateFieldsMetadata].
//
// Kibana API: POST /api/data_views/data_view/{viewId}
//
// Kibana API docs: https://www.elastic.co/docs/api/doc/kibana/operation/operation-updatedataviewdefault
func (s *DataViewsService) Update(ctx context.Context, id string, dv *DataView, opt *UpdateDataViewOptions, opts ...RequestOption) (*DataView, *Response, error) {
	if err := requireID("data view ID", id); err != nil {
		return nil, nil, err
	}
	if dv == nil {
		return nil, nil, errors.New("kibana: data view must not be nil")
	}
	body := &dataViewUpdate{DataView: dataViewUpdateFields{
		Title:           dv.Title,
		Name:            dv.Name,
		TimeFieldName:   dv.TimeFieldName,
		AllowNoIndex:    dv.AllowNoIndex,
		SourceFilters:   dv.SourceFilters,
		FieldFormats:    dv.FieldFormats,
		RuntimeFieldMap: dv.RuntimeFieldMap,
		Type:            dv.Type,
		TypeMeta:        dv.TypeMeta,
	}}
	if opt != nil {
		body.RefreshFields = opt.RefreshFields
	}
	return s.dataView(ctx, http.MethodPost, pathf("/api/data_views/data_view/%s", id), body, nil, opts)
}

