// DataViewsService handles communication with the data view methods of the
// Kibana API. Data views belong to a space: use [Client.InSpace] to manage
// the data views of another space.
//
// Kibana API docs: https://www.elastic.co/docs/api/doc/kibana/group/endpoint-data-views
type DataViewsService service

// DataView is a Kibana data view (formerly index pattern): the indices that
// Discover and visualizations query, and how their fields are shown. The
// same type is used for reads and writes; see [DataViewsService.Create] and
// [DataViewsService.Update] for the fields each one sends.
type DataView struct {
	// ID is generated by Kibana if it is empty when creating the data view.
	ID string `json:"id,omitempty"`

	// Title is the index pattern, such as "logs-*" or "logs-1,logs-2".
	// Required when creating.
	Title string `json:"title"`

	// Name is the display name. Kibana uses Title if it is empty.
	Name          string `json:"name,omitempty"`
	TimeFieldName string `json:"timeFieldName,omitempty"`

	// AllowNoIndex keeps the data view usable when no index matches Title.
	AllowNoIndex bool `json:"allowNoIndex,omitempty"`

	// SourceFilters lists the fields to hide in Discover, as patterns.
	SourceFilters []DataViewSourceFilter `json:"sourceFilters,omitempty"`

	// FieldFormats maps field names to their display format.
	FieldFormats map[string]DataViewFieldFormat `json:"fieldFormats,omitempty"`

	// RuntimeFieldMap maps the names of the data view's runtime fields to
	// their definition.
	RuntimeFieldMap map[string]RuntimeField `json:"runtimeFieldMap,omitempty"`

	// FieldAttrs maps field names to their custom labels, descriptions and
	// popularity. It is only written by Create.
	FieldAttrs map[string]DataViewFieldAttrs `json:"fieldAttrs,omitempty"`

	// Namespaces lists the spaces of the data view. It is only written by
	// Create: use [SpacesService.UpdateObjectsSpaces] to share a data view.
	Namespaces []string `json:"namespaces,omitempty"`

	// Type is "rollup" for rollup data views, and empty otherwise.
	Type     string            `json:"type,omitempty"`
	TypeMeta *DataViewTypeMeta `json:"typeMeta,omitempty"`

	// Fields maps the field names to their specification, including the
	// runtime fields. Set by Kibana.
	Fields map[string]DataViewField `json:"fields,omitempty"`

	// AllowHidden includes hidden and system indices, such as .alerts-*.
	// It is only written by Create.
	AllowHidden bool `json:"allowHidden,omitempty"`

	// Version identifies the revision of the data view. Set by Kibana.
	Version string `json:"version,omitempty"`
}

// DataViewSourceFilter is a field pattern that Discover hides.
type DataViewSourceFilter struct {
	Value string `json:"value"`
}

// DataViewFieldFormat is the display format of a field, such as
// {ID: "number", Params: {"pattern": "0,0.00"}}.
type DataViewFieldFormat struct {
	ID     string          `json:"id"`
	Params json.RawMessage `json:"params,omitempty"`
}

// DataViewFieldAttrs holds the custom attributes of a field.
type DataViewFieldAttrs struct {
	CustomLabel       string `json:"customLabel,omitempty"`
	CustomDescription string `json:"customDescription,omitempty"`

	// Count is the popularity of the field.
	Count int `json:"count,omitempty"`
}

// DataViewTypeMeta holds the rollup settings of a rollup data view.
type DataViewTypeMeta struct {
	Aggs   json.RawMessage `json:"aggs"`
	Params json.RawMessage `json:"params"`
}

// RuntimeFieldType is the type of a runtime field.
type RuntimeFieldType string

// Runtime field types. Elasticsearch may support others.
const (
	RuntimeFieldTypeKeyword   RuntimeFieldType = "keyword"
	RuntimeFieldTypeLong      RuntimeFieldType = "long"
	RuntimeFieldTypeDouble    RuntimeFieldType = "double"
	RuntimeFieldTypeDate      RuntimeFieldType = "date"
	RuntimeFieldTypeIP        RuntimeFieldType = "ip"
	RuntimeFieldTypeBoolean   RuntimeFieldType = "boolean"
	RuntimeFieldTypeGeoPoint  RuntimeFieldType = "geo_point"
	RuntimeFieldTypeComposite RuntimeFieldType = "composite"
)

// RuntimeField is the definition of a runtime field: a field computed by a
// Painless script when it is queried.
type RuntimeField struct {
	Type RuntimeFieldType `json:"type,omitempty"`

	// Script computes the field. Without it, the field has the value of
	// the source field with the same name.
	Script *RuntimeFieldScript `json:"script,omitempty"`

	// Fields lists the subfields of a composite runtime field, emitted by
	// the script.
	Fields map[string]RuntimeSubField `json:"fields,omitempty"`

	// CustomLabel, CustomDescription, Popularity and Format are the field's
	// metadata. The runtime field methods, such as
	// [DataViewsService.CreateRuntimeField], store them in
	// DataView.FieldAttrs and FieldFormats, and do not return them here. In
	// DataView.RuntimeFieldMap, Kibana stores and returns them with the
	// runtime field.
	CustomLabel       string               `json:"customLabel,omitempty"`
	CustomDescription string               `json:"customDescription,omitempty"`
	Popularity        int                  `json:"popularity,omitempty"`
	Format            *DataViewFieldFormat `json:"format,omitempty"`
}

// RuntimeFieldScript is the Painless script of a runtime field, such as
// `emit(doc["status"].value)`.
type RuntimeFieldScript struct {
	Source string `json:"source"`
}

// RuntimeSubField is a subfield of a composite runtime field. Its metadata
// is stored like that of a [RuntimeField], under the name
// "<field>.<subfield>".
type RuntimeSubField struct {
	Type RuntimeFieldType `json:"type"`

	CustomLabel       string               `json:"customLabel,omitempty"`
	CustomDescription string               `json:"customDescription,omitempty"`
	Popularity        int                  `json:"popularity,omitempty"`
	Format            *DataViewFieldFormat `json:"format,omitempty"`
}

// DataViewField is the specification of a field of a data view, as Kibana
// returns it.
type DataViewField struct {
	Name string `json:"name"`

	// Type is the Kibana field type, such as "string", "number" or
	// "date"; ESTypes are the Elasticsearch types.
	Type    string   `json:"type"`
	ESTypes []string `json:"esTypes,omitempty"`

	Searchable        bool `json:"searchable"`
	Aggregatable      bool `json:"aggregatable"`
	ReadFromDocValues bool `json:"readFromDocValues"`
	Scripted          bool `json:"scripted"`

	// IsMapped is false for fields that are not in the index mappings.
	IsMapped *bool `json:"isMapped,omitempty"`

	CustomLabel       string               `json:"customLabel,omitempty"`
	CustomDescription string               `json:"customDescription,omitempty"`
	Count             int                  `json:"count"`
	Format            *DataViewFieldFormat `json:"format,omitempty"`

	// RuntimeField is set for runtime fields.
	RuntimeField *RuntimeField `json:"runtimeField,omitempty"`

	// SubType describes multi-fields and nested fields.
	SubType json.RawMessage `json:"subType,omitempty"`
}

// DataViewSummary is a data view as [DataViewsService.List] returns it.
type DataViewSummary struct {
	ID         string            `json:"id"`
	Title      string            `json:"title"`
	Name       string            `json:"name"`
	Namespaces []string          `json:"namespaces,omitempty"`
	TypeMeta   *DataViewTypeMeta `json:"typeMeta,omitempty"`

	// Managed data views are managed by Kibana or an integration. Kibana
	// 8.19 does not return it.
	Managed bool `json:"managed,omitempty"`
}

// dataViewEnvelope is the {"data_view": ...} form of data view requests and
// responses.
type dataViewEnvelope[T any] struct {
	DataView T `json:"data_view"`
}

// dataViewCreate is the body of a create request. Kibana rejects unknown
// fields and null values.
type dataViewCreate struct {
	DataView dataViewCreateFields `json:"data_view"`
	Override bool                 `json:"override,omitempty"`
}

type dataViewCreateFields struct {
	ID              string                         `json:"id,omitempty"`
	Title           string                         `json:"title"`
	Name            string                         `json:"name,omitempty"`
	TimeFieldName   string                         `json:"timeFieldName,omitempty"`
	AllowNoIndex    bool                           `json:"allowNoIndex,omitempty"`
	SourceFilters   []DataViewSourceFilter         `json:"sourceFilters,omitempty"`
	FieldFormats    map[string]DataViewFieldFormat `json:"fieldFormats,omitempty"`
	RuntimeFieldMap map[string]RuntimeField        `json:"runtimeFieldMap,omitempty"`
	FieldAttrs      map[string]DataViewFieldAttrs  `json:"fieldAttrs,omitempty"`
	Namespaces      []string                       `json:"namespaces,omitempty"`
	AllowHidden     bool                           `json:"allowHidden,omitempty"`
	Type            string                         `json:"type,omitempty"`
	TypeMeta        *DataViewTypeMeta              `json:"typeMeta,omitempty"`
}

// dataViewUpdate is the body of an update request. Kibana keeps the fields
// that are left out, rejects unknown fields and null values, and saves an
// empty title.
type dataViewUpdate struct {
	DataView      dataViewUpdateFields `json:"data_view"`
	RefreshFields bool                 `json:"refresh_fields,omitempty"`
}

type dataViewUpdateFields struct {
	// Title is left out when empty, which keeps the stored title.
	Title string `json:"title,omitempty"`

	// Name and TimeFieldName are always sent, so that "" clears them.
	Name          string `json:"name"`
	TimeFieldName string `json:"timeFieldName"`
	AllowNoIndex  bool   `json:"allowNoIndex"`

	// The collections are left out when nil, which keeps them, and sent
	// when empty, which clears them.
	SourceFilters   []DataViewSourceFilter         `json:"sourceFilters,omitzero"`
	FieldFormats    map[string]DataViewFieldFormat `json:"fieldFormats,omitzero"`
	RuntimeFieldMap map[string]RuntimeField        `json:"runtimeFieldMap,omitzero"`

	Type     string            `json:"type,omitempty"`
	TypeMeta *DataViewTypeMeta `json:"typeMeta,omitempty"`
}

